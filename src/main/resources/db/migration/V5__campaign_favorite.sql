-- 회원이 관심 있는 캠페인을 저장하는 찜 테이블입니다.
-- 같은 회원이 같은 캠페인을 두 번 찜할 수 없도록 (member_id, campaign_id)에 유니크 제약을 둡니다.
-- 회원 또는 캠페인이 지워지면 찜도 함께 정리됩니다.
CREATE TABLE public.campaign_favorite (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id bigint NOT NULL,
    campaign_id bigint NOT NULL,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT uk_campaign_favorite_member_campaign UNIQUE (member_id, campaign_id),
    CONSTRAINT fk_campaign_favorite_member FOREIGN KEY (member_id)
        REFERENCES public.member (id) ON DELETE CASCADE,
    CONSTRAINT fk_campaign_favorite_campaign FOREIGN KEY (campaign_id)
        REFERENCES public.collaboration_campaign (id) ON DELETE CASCADE
);

-- 캠페인별 찜 수를 셀 때 사용하는 인덱스입니다.
CREATE INDEX idx_campaign_favorite_campaign ON public.campaign_favorite (campaign_id);
