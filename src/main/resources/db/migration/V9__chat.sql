-- 브랜드·참여자·운영자가 주고받는 채팅입니다.
-- 방 종류
--   APPLICATION: 캠페인 신청 한 건에 대한 참여자 ↔ 브랜드 대화(운영자도 열람·참여 가능). 신청마다 하나입니다.
--   SUPPORT: 회원(참여자·브랜드) ↔ 운영자 1:1 문의. 회원마다 하나입니다.
CREATE TABLE public.chat_room (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_type varchar(20) NOT NULL,
    application_id bigint,
    owner_member_id bigint,
    title varchar(200) NOT NULL,
    last_message_at timestamp(6) without time zone,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT ck_chat_room_type CHECK (room_type IN ('APPLICATION', 'SUPPORT')),
    CONSTRAINT ck_chat_room_target CHECK (
        (room_type = 'APPLICATION' AND application_id IS NOT NULL)
        OR (room_type = 'SUPPORT' AND owner_member_id IS NOT NULL)),
    CONSTRAINT uk_chat_room_application UNIQUE (application_id),
    CONSTRAINT fk_chat_room_application FOREIGN KEY (application_id)
        REFERENCES public.campaign_application (id) ON DELETE CASCADE,
    CONSTRAINT fk_chat_room_owner FOREIGN KEY (owner_member_id)
        REFERENCES public.member (id) ON DELETE CASCADE
);
-- 회원마다 운영자 문의방은 하나만 둡니다.
CREATE UNIQUE INDEX uk_chat_room_support_owner ON public.chat_room (owner_member_id)
    WHERE room_type = 'SUPPORT';
CREATE INDEX idx_chat_room_last_message ON public.chat_room (last_message_at DESC);

-- 방에 참여한 회원과 '어디까지 읽었는지'입니다. 운영자는 방을 처음 열 때 참여자로 추가됩니다.
CREATE TABLE public.chat_participant (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id bigint NOT NULL,
    member_id bigint NOT NULL,
    participant_role varchar(20) NOT NULL,
    last_read_message_id bigint NOT NULL DEFAULT 0,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT ck_chat_participant_role CHECK (participant_role IN ('CREATOR', 'BRAND', 'ADMIN', 'MEMBER')),
    CONSTRAINT uk_chat_participant UNIQUE (room_id, member_id),
    CONSTRAINT fk_chat_participant_room FOREIGN KEY (room_id)
        REFERENCES public.chat_room (id) ON DELETE CASCADE,
    CONSTRAINT fk_chat_participant_member FOREIGN KEY (member_id)
        REFERENCES public.member (id) ON DELETE CASCADE
);
CREATE INDEX idx_chat_participant_member ON public.chat_participant (member_id);

-- 메시지입니다. 보낸 사람의 역할을 함께 남겨 화면에 '브랜드'·'운영자' 표시를 붙입니다.
CREATE TABLE public.chat_message (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id bigint NOT NULL,
    sender_member_id bigint,
    sender_role varchar(20) NOT NULL,
    body varchar(2000) NOT NULL,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT ck_chat_message_role CHECK (sender_role IN ('CREATOR', 'BRAND', 'ADMIN', 'MEMBER')),
    CONSTRAINT fk_chat_message_room FOREIGN KEY (room_id)
        REFERENCES public.chat_room (id) ON DELETE CASCADE,
    CONSTRAINT fk_chat_message_sender FOREIGN KEY (sender_member_id)
        REFERENCES public.member (id) ON DELETE SET NULL
);
CREATE INDEX idx_chat_message_room ON public.chat_message (room_id, id);
