-- 기간 연장 기록: 신청 하나의 체험 기간·콘텐츠 마감을 늘릴 때마다 한 줄씩 남깁니다.
-- - PARTICIPANT_REQUEST: 참여자가 요청하고 업체(또는 운영자)가 승인한 연장(신청당 1회)
-- - SELLER / ADMIN: 업체나 운영자가 사정을 듣고 직접 늘린 연장(횟수 제한 없음)
-- 운영자는 회원 상세에서 이 기록으로 참여자의 연장 횟수를 확인하고, 지나치게 잦으면 제재를 판단합니다.
CREATE TABLE campaign_period_extension (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  application_id bigint NOT NULL REFERENCES campaign_application (id),
  member_id bigint NOT NULL REFERENCES member (id),
  days integer NOT NULL,
  reason varchar(500) NOT NULL,
  source varchar(30) NOT NULL,
  extended_by_member_id bigint REFERENCES member (id),
  previous_experience_end timestamp(6),
  new_experience_end timestamp(6),
  previous_deadline timestamp(6) NOT NULL,
  new_deadline timestamp(6) NOT NULL,
  created_at timestamp(6) NOT NULL,
  CONSTRAINT ck_campaign_period_extension_days CHECK (days BETWEEN 1 AND 30),
  CONSTRAINT ck_campaign_period_extension_source
    CHECK (source IN ('PARTICIPANT_REQUEST', 'SELLER', 'ADMIN'))
);
CREATE INDEX ix_campaign_period_extension_member
  ON campaign_period_extension (member_id, created_at DESC);
CREATE INDEX ix_campaign_period_extension_application
  ON campaign_period_extension (application_id, created_at DESC);

-- 이미 승인된 참여자 요청을 기록으로 옮깁니다(체험 기간은 V19 이후 승인분만 값이 있습니다).
INSERT INTO campaign_period_extension (
  application_id, member_id, days, reason, source, extended_by_member_id,
  previous_experience_end, new_experience_end, previous_deadline, new_deadline, created_at)
SELECT e.application_id, e.member_id, e.days, e.reason, 'PARTICIPANT_REQUEST', e.decided_by_member_id,
       a.experience_extended_until - make_interval(days => e.days), a.experience_extended_until,
       e.previous_deadline, e.previous_deadline + make_interval(days => e.days),
       coalesce(e.decided_at, e.created_at)
FROM campaign_extension_request e
JOIN campaign_application a ON a.id = e.application_id
WHERE e.status = 'APPROVED';
