-- AI(LLM) 호출 사용량 기록입니다. 운영 감사 기록(audit_log)과 나눠, 업체가 초안을 자주 만들어도 운영 기록이 밀려나지 않게 합니다.
-- 요청 원문과 AI 답은 저장하지 않고 모델·토큰 수·결과만 남깁니다. 하루 사용 횟수 제한과 비용 집계에 씁니다.
CREATE TABLE ai_usage_log (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  member_id bigint NOT NULL REFERENCES member(id),
  feature varchar(40) NOT NULL,
  model varchar(80) NOT NULL,
  input_tokens integer NOT NULL CHECK (input_tokens >= 0),
  output_tokens integer NOT NULL CHECK (output_tokens >= 0),
  outcome varchar(20) NOT NULL,
  created_at timestamp(6) NOT NULL
);
CREATE INDEX idx_ai_usage_log_member_feature_created ON ai_usage_log (member_id, feature, created_at);

COMMENT ON TABLE ai_usage_log IS 'AI(LLM) 호출 사용량: 회원·기능별 하루 횟수 제한과 토큰 집계';
COMMENT ON COLUMN ai_usage_log.feature IS '기능 이름(예: CAMPAIGN_DRAFT)';
COMMENT ON COLUMN ai_usage_log.outcome IS '결과: SUCCESS(초안 반환) · INVALID_ANSWER(형식 오류) · TRUNCATED(길이 제한으로 잘림)';
