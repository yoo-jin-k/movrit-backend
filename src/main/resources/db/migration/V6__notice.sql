-- 운영자가 작성하는 공지사항 테이블입니다.
-- 게시(published)된 공지만 사용자 공지 목록에 보이며, 상단 고정(pinned) 공지가 먼저 나옵니다.
CREATE TABLE public.notice (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title varchar(200) NOT NULL,
    body text NOT NULL,
    category varchar(20) NOT NULL DEFAULT 'NOTICE',
    pinned boolean NOT NULL DEFAULT false,
    published boolean NOT NULL DEFAULT false,
    published_at timestamp(6) without time zone,
    author_member_id bigint,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT ck_notice_category CHECK (category IN ('NOTICE', 'GUIDE', 'EVENT')),
    CONSTRAINT fk_notice_author FOREIGN KEY (author_member_id)
        REFERENCES public.member (id) ON DELETE SET NULL
);

-- 사용자 목록(게시된 공지를 고정·최신 순으로)에 쓰는 인덱스입니다.
CREATE INDEX idx_notice_published ON public.notice (published, pinned, published_at);
