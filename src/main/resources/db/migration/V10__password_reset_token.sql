-- 비밀번호 재설정 링크용 일회성 토큰입니다.
-- 토큰 원문은 저장하지 않고 SHA-256 해시만 보관합니다. 30분 뒤 만료되며 한 번 쓰면 다시 쓸 수 없습니다.
CREATE TABLE public.password_reset_token (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id bigint NOT NULL,
    token_hash varchar(64) NOT NULL,
    expires_at timestamp(6) without time zone NOT NULL,
    used_at timestamp(6) without time zone,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT uk_password_reset_token_hash UNIQUE (token_hash),
    CONSTRAINT fk_password_reset_token_member FOREIGN KEY (member_id)
        REFERENCES public.member (id) ON DELETE CASCADE
);
CREATE INDEX idx_password_reset_token_member ON public.password_reset_token (member_id, created_at);
