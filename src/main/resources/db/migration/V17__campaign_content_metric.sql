-- 제출한 콘텐츠 게시물의 성과(조회수·좋아요·댓글 수)를 날짜별로 기록합니다.
-- 외부 SNS 지표를 자동으로 가져오지 않으므로 참여자나 캠페인 업체가 게시물에서 확인한 숫자를 직접 입력합니다.
-- 재제출하면 링크 행이 새로 만들어지므로 링크 ID 대신 (제출 건, 게시물 주소)로 묶습니다.
-- 같은 게시물·같은 날짜는 한 줄만 두고, 다시 입력하면 그 줄을 고칩니다.
CREATE TABLE public.campaign_content_metric (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    submission_id bigint NOT NULL,
    channel_type varchar(30) NOT NULL,
    content_url varchar(1000) NOT NULL,
    view_count integer NOT NULL DEFAULT 0,
    like_count integer NOT NULL DEFAULT 0,
    comment_count integer NOT NULL DEFAULT 0,
    measured_on date NOT NULL,
    recorded_by_member_id bigint,
    recorded_by_role varchar(20) NOT NULL,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT uk_campaign_content_metric_day UNIQUE (submission_id, content_url, measured_on),
    CONSTRAINT ck_campaign_content_metric_counts
        CHECK (view_count >= 0 AND like_count >= 0 AND comment_count >= 0),
    CONSTRAINT ck_campaign_content_metric_role CHECK (recorded_by_role IN ('CREATOR', 'SELLER')),
    CONSTRAINT fk_campaign_content_metric_submission FOREIGN KEY (submission_id)
        REFERENCES public.campaign_content_submission (id) ON DELETE CASCADE,
    CONSTRAINT fk_campaign_content_metric_member FOREIGN KEY (recorded_by_member_id)
        REFERENCES public.member (id) ON DELETE SET NULL
);
CREATE INDEX idx_campaign_content_metric_submission
    ON public.campaign_content_metric (submission_id, measured_on DESC);
