-- 커뮤니티 게시판(글·댓글)입니다.
-- 게시판: free(MOVRIT 톡톡)·neighbor(우리 친구할까요?)는 회원 누구나, guide(MOVRIT 소식)·event(이벤트)는 운영자만 글을 씁니다.
-- 글·댓글은 지우지 않고 deleted_at으로 숨깁니다. 운영자는 부적절한 글을 hidden으로 내릴 수 있습니다.
CREATE TABLE public.community_post (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    board varchar(20) NOT NULL,
    category varchar(20) NOT NULL,
    title varchar(100) NOT NULL,
    body varchar(5000) NOT NULL,
    author_member_id bigint,
    view_count integer NOT NULL DEFAULT 0,
    comment_count integer NOT NULL DEFAULT 0,
    hidden boolean NOT NULL DEFAULT false,
    deleted_at timestamp(6) without time zone,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT ck_community_post_board CHECK (board IN ('free', 'neighbor', 'guide', 'event')),
    CONSTRAINT fk_community_post_author FOREIGN KEY (author_member_id)
        REFERENCES public.member (id) ON DELETE SET NULL
);
CREATE INDEX idx_community_post_board ON public.community_post (board, id DESC);

CREATE TABLE public.community_comment (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id bigint NOT NULL,
    author_member_id bigint,
    body varchar(1000) NOT NULL,
    deleted_at timestamp(6) without time zone,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT fk_community_comment_post FOREIGN KEY (post_id)
        REFERENCES public.community_post (id) ON DELETE CASCADE,
    CONSTRAINT fk_community_comment_author FOREIGN KEY (author_member_id)
        REFERENCES public.member (id) ON DELETE SET NULL
);
CREATE INDEX idx_community_comment_post ON public.community_comment (post_id, id);
