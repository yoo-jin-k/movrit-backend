-- SNS 소개글 인증 코드: 회원이 받은 코드를 블로그·인스타그램 소개글에 넣으면 서버가 공개 정보에서 코드를 확인해 채널을 '확인됨'으로 등록합니다.
-- - 코드는 회원·서비스마다 발급하고 24시간 동안 쓸 수 있으며, 한 코드로 확인을 10번까지 시도할 수 있습니다(하루 5번까지 새로 발급).
-- - 자동으로 확인할 수 없는 인스타그램 계정(개인 계정 등)은 운영자 확인으로 넘기고, 운영자는 소개글에 이 코드가 있는지 봅니다.
CREATE TABLE channel_bio_code (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  member_id bigint NOT NULL REFERENCES member (id) ON DELETE CASCADE,
  provider varchar(20) NOT NULL,
  code varchar(20) NOT NULL,
  expires_at timestamp(6) NOT NULL,
  check_count integer NOT NULL DEFAULT 0,
  used_at timestamp(6),
  created_at timestamp(6) NOT NULL,
  CONSTRAINT uk_channel_bio_code_code UNIQUE (code),
  CONSTRAINT ck_channel_bio_code_provider CHECK (provider IN ('INSTAGRAM', 'NAVER_BLOG')),
  CONSTRAINT ck_channel_bio_code_checks CHECK (check_count >= 0)
);
CREATE INDEX ix_channel_bio_code_member ON channel_bio_code (member_id, provider, created_at DESC);

-- 연결 방법에 '소개글 코드'(BIO_CODE)를 더하고, 확인에 쓴 코드를 남겨 운영자가 소개글과 대조할 수 있게 합니다.
ALTER TABLE member_channel_connection DROP CONSTRAINT IF EXISTS ck_member_channel_connection_method;
ALTER TABLE member_channel_connection ADD CONSTRAINT ck_member_channel_connection_method
  CHECK (connection_method IN ('OAUTH', 'MANUAL', 'BIO_CODE'));
ALTER TABLE member_channel_connection ADD COLUMN verification_code varchar(20);
