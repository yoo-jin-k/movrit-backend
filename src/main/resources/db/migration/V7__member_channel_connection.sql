-- 회원이 실제 SNS 계정 로그인으로 연결한 채널(인스타그램·유튜브·네이버 블로그) 기록입니다.
-- 접근 토큰은 저장하지 않습니다. 연결할 때 받은 계정 정보와 팔로워·구독자 수만 남기고, 최신 값이 필요하면 다시 연결합니다.
CREATE TABLE public.member_channel_connection (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id bigint NOT NULL,
    provider varchar(20) NOT NULL,
    external_id varchar(100) NOT NULL,
    account_name varchar(100),
    profile_url varchar(500),
    follower_count bigint,
    connected_at timestamp(6) without time zone NOT NULL,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT ck_member_channel_connection_provider
        CHECK (provider IN ('INSTAGRAM', 'YOUTUBE', 'NAVER_BLOG')),
    CONSTRAINT ck_member_channel_connection_follower CHECK (follower_count IS NULL OR follower_count >= 0),
    -- 회원마다 서비스별로 계정 하나만 연결합니다.
    CONSTRAINT uk_member_channel_connection_member UNIQUE (member_id, provider),
    -- 같은 SNS 계정을 두 회원이 함께 쓰지 못하게 합니다.
    CONSTRAINT uk_member_channel_connection_account UNIQUE (provider, external_id),
    CONSTRAINT fk_member_channel_connection_member FOREIGN KEY (member_id)
        REFERENCES public.member (id) ON DELETE CASCADE
);
