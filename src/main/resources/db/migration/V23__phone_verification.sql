-- 휴대폰 번호 인증(인증번호 6자리): 번호를 입력하면 인증번호를 보내고, 맞게 입력하면 회원 연락처를 '인증됨'으로 바꿉니다.
-- - 인증번호는 원문 대신 해시로 저장하고, 만료·사용·무효화 시각과 틀린 입력 횟수로 사용 가능 여부를 판단합니다(이메일 인증과 같은 방식).
-- - 같은 번호로 하루에 보낼 수 있는 횟수를 세기 위해 요청한 번호를 함께 남깁니다.
-- - 인증된 번호는 회원 한 명만 가질 수 있습니다(같은 사람이 여러 계정으로 패널티를 피하지 못하게).
CREATE TABLE phone_verification_challenge (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  member_id bigint NOT NULL REFERENCES member (id) ON DELETE CASCADE,
  phone varchar(20) NOT NULL,
  code_hash varchar(100) NOT NULL,
  expires_at timestamp(6) NOT NULL,
  consumed_at timestamp(6),
  invalidated_at timestamp(6),
  attempt_count integer NOT NULL DEFAULT 0,
  created_at timestamp(6) NOT NULL,
  updated_at timestamp(6) NOT NULL,
  CONSTRAINT ck_phone_verification_attempt_count CHECK (attempt_count >= 0)
);
CREATE INDEX ix_phone_verification_member ON phone_verification_challenge (member_id, created_at DESC);
CREATE INDEX ix_phone_verification_phone ON phone_verification_challenge (phone, created_at DESC);

-- 회원 연락처 인증 시각. 연락처를 바꾸면 비웁니다.
ALTER TABLE member ADD COLUMN phone_verified_at timestamp(6);
CREATE UNIQUE INDEX uk_member_verified_phone ON member (phone) WHERE phone_verified_at IS NOT NULL;
