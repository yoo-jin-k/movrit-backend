package com.movrit.movrit.preorder;

import static org.junit.jupiter.api.Assertions.*;

import com.movrit.movrit.preorder.entity.Preorder;
import jakarta.persistence.JoinTable;
import java.nio.file.Files;
import java.nio.file.Path;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.SQLException;
import java.util.UUID;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.condition.EnabledIfEnvironmentVariable;

/** 통합 DB 안의 격리 스키마에서 실행하고 전체 트랜잭션을 되돌리는 SQL 호환 회귀 검수입니다. */
@EnabledIfEnvironmentVariable(named = "MOVRIT_PREORDER_MIGRATION_TEST", matches = "true")
class PreorderSaleVariantMigrationTest {
  @Test
  void preservesLegacyPricesAndOrderReferencesWhileAllowingNewSkuLinks() throws Exception {
    String url =
        System.getenv()
            .getOrDefault(
                "INTEGRATION_DB_URL", "jdbc:postgresql://localhost:5432/movrit_integration");
    assertTrue(url.endsWith("/movrit_integration"), "통합 DB에서만 실행합니다.");
    try (Connection connection =
        DriverManager.getConnection(
            url,
            System.getenv().getOrDefault("INTEGRATION_DB_USERNAME", "movrit_user"),
            System.getenv("INTEGRATION_DB_PASSWORD"))) {
      connection.setAutoCommit(false);
      try {
        String schema = "qa_preorder_" + UUID.randomUUID().toString().replace("-", "");
        execute(connection, "CREATE SCHEMA " + schema);
        execute(connection, "SET LOCAL search_path TO " + schema);
        execute(connection, "CREATE TABLE preorder(id BIGINT PRIMARY KEY)");
        execute(connection, "CREATE TABLE product_variant(id BIGINT PRIMARY KEY)");
        execute(
            connection,
            "CREATE TABLE preorder_variant(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                + "preorder_id BIGINT REFERENCES preorder(id), product_variant_id BIGINT REFERENCES product_variant(id), "
                + "preorder_price NUMERIC NOT NULL, UNIQUE(preorder_id, product_variant_id))");
        execute(
            connection,
            "CREATE TABLE order_item(id BIGINT PRIMARY KEY, "
                + "preorder_variant_id BIGINT REFERENCES preorder_variant(id))");
        execute(connection, "INSERT INTO preorder VALUES(1),(2)");
        execute(connection, "INSERT INTO product_variant VALUES(10),(11)");
        execute(connection, "INSERT INTO preorder_variant VALUES(100,1,10,12345)");
        execute(connection, "INSERT INTO order_item VALUES(200,100)");

        // 기존 Hibernate의 두 열 INSERT가 레거시 가격 필수 제약과 충돌하는지 재현합니다.
        var beforeFailure = connection.setSavepoint();
        SQLException original =
            assertThrows(
                SQLException.class,
                () ->
                    execute(
                        connection,
                        "INSERT INTO preorder_variant(preorder_id,product_variant_id) VALUES(2,11)"));
        assertEquals("23502", original.getSQLState());
        connection.rollback(beforeFailure);

        String migration = Files.readString(Path.of("docs/sql/feature-preorder-sale-variants.sql"));
        execute(connection, migration);
        execute(connection, migration); // 반복 적용해도 중복 연결이나 가격 변경이 없어야 합니다.
        String mappedTable =
            Preorder.class.getDeclaredField("saleVariants").getAnnotation(JoinTable.class).name();
        assertEquals("preorder_sale_variant", mappedTable);
        execute(
            connection,
            "INSERT INTO " + mappedTable + "(preorder_id,product_variant_id) VALUES(2,11)");
        assertEquals(2, scalar(connection, "SELECT count(*) FROM " + mappedTable));
        assertEquals(1, scalar(connection, "SELECT count(*) FROM preorder_variant"));
        assertEquals(
            12345, scalar(connection, "SELECT preorder_price FROM preorder_variant WHERE id=100"));
        assertEquals(
            1,
            scalar(
                connection,
                "SELECT count(*) FROM order_item oi JOIN preorder_variant pv "
                    + "ON pv.id=oi.preorder_variant_id WHERE pv.id=100"));
        // 현재 허용 연결의 제거가 과거 판매조건 및 주문 참조를 지우지 않아야 합니다.
        execute(connection, "DELETE FROM " + mappedTable + " WHERE preorder_id=1");
        execute(connection, migration);
        assertEquals(
            0, scalar(connection, "SELECT count(*) FROM " + mappedTable + " WHERE preorder_id=1"));
        assertEquals(1, scalar(connection, "SELECT count(*) FROM preorder_variant WHERE id=100"));
        assertEquals(
            1, scalar(connection, "SELECT count(*) FROM order_item WHERE preorder_variant_id=100"));
      } finally {
        connection.rollback();
      }
    }
  }

  private static void execute(Connection connection, String sql) throws SQLException {
    try (var statement = connection.createStatement()) {
      statement.execute(sql);
    }
  }

  private static long scalar(Connection connection, String sql) throws SQLException {
    try (var statement = connection.createStatement();
        var rows = statement.executeQuery(sql)) {
      assertTrue(rows.next());
      return rows.getLong(1);
    }
  }
}
