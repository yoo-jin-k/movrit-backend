BEGIN;
CREATE TABLE campaign_visit_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id BIGINT NOT NULL REFERENCES collaboration_campaign(id),
    actor_member_id BIGINT NOT NULL REFERENCES member(id),
    presentation_version BIGINT NOT NULL,
    before_location_json TEXT,
    after_location_json TEXT,
    legacy_place_name TEXT,
    legacy_address TEXT,
    legacy_after_place_name TEXT,
    legacy_after_address TEXT,
    changed_at TIMESTAMP NOT NULL
);
CREATE INDEX idx_campaign_visit_history_campaign ON campaign_visit_history(campaign_id,id);
CREATE TABLE campaign_visit_snapshot (
    application_id BIGINT PRIMARY KEY REFERENCES campaign_application(id),
    campaign_id BIGINT NOT NULL REFERENCES collaboration_campaign(id),
    presentation_version BIGINT NOT NULL,
    location_json TEXT,
    visit_guide TEXT,
    legacy_place_name TEXT,
    legacy_address TEXT,
    captured_at TIMESTAMP NOT NULL
);
COMMIT;
